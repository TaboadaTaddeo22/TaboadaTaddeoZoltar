    // Modifiche della comboBox (es. aggiunta delle personalità)
    private void modificaComboBox() {
        cmbPersonalita.addItem("Zoltar");
        cmbPersonalita.addItem("Eldego");
        cmbPersonalita.addItem("Sindaco");
        cmbPersonalita.setSelectedIndex(0);
        impostaImmagine(0);
    }
    
    // Quando l'utente pone una domanda parte l'animazione gif relativa alla personalità scelta per 2,5 secondi
    private void animaImmagine() {
        ImageIcon immagine = null;
        switch (cmbPersonalita.getSelectedIndex()) {
            case 0:
                immagine = new ImageIcon(getClass().getResource("zoltar_quadrato.gif"));
                break;
            case 1:
                immagine = new ImageIcon(getClass().getResource("eldego_quadrato.gif"));
                break;
            case 2:
                immagine = new ImageIcon(getClass().getResource("sindaco_quadrato.gif"));
                break;
            default:
                return;
        }

        // Ferma un'eventuale animazione precedente
        if (timerGif != null) {
            timerGif.stop();
        }
        
        lblImmagine.setIcon(immagine);

        // Durata dell'animazione in millisecondi
        timerGif = new javax.swing.Timer(2500, e -> {
            impostaImmagine(cmbPersonalita.getSelectedIndex());
        });

        timerGif.setRepeats(false);
        timerGif.start();
    }
    
    // Quando l'utente cambia personalità cambia l'immagine corrispettiva
    private void impostaImmagine(int indice) {
        ImageIcon immagine = null;
        switch (indice) {
            case 0:
                immagine = new ImageIcon(getClass().getResource("zoltar_quadrato.png"));
                break;
            case 1:
                immagine = new ImageIcon(getClass().getResource("eldego_quadrato.png"));
                break;
            case 2:
                immagine = new ImageIcon(getClass().getResource("sindaco_quadrato.png"));
                break;
            default:
                break;
        }
        
        Image img = immagine.getImage();
        Image ridimensionata = img.getScaledInstance(
            lblImmagine.getWidth(),
            lblImmagine.getHeight(),
            Image.SCALE_SMOOTH
        );

        lblImmagine.setIcon(new ImageIcon(ridimensionata));
    }
    
    // Vengono fatti partire il server ed il client con dei thread
    public void iniziaZoltar() {
        new Thread(() -> {
            try {
                s.avvia();
            } catch (IOException ex) {
                ex.printStackTrace();
            }
        }).start();
        new Thread(() -> {
            try {
                c.utente();
            } catch (IOException ex) {
                ex.printStackTrace();
            }
        }).start();
    }

